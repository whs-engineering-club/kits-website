// Generates site/data.js from data/kits.mjs so the static site works without the backend.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { kits, curriculum, site, planInfo } from '../data/kits.mjs';

const out = fileURLToPath(new URL('../site/data.js', import.meta.url));
writeFileSync(out, `// Generated by scripts/build-data.mjs — do not edit.\nwindow.KITS_DATA = ${JSON.stringify({ site, kits, curriculum, planInfo })};\n`);
console.log(`Wrote ${out}`);
